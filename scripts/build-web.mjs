import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
await import('../build.mjs');
await fs.mkdir(path.join(root,'backend/src'),{recursive:true});
await fs.copyFile(path.join(root,'publish/index.html'),path.join(root,'backend/src/planner.html'));
await import('../backend/build.mjs');
const config=JSON.parse(await fs.readFile(path.join(root,'pages.config.json'),'utf8'));
const origin=new URL(config.managementOrigin);
if(origin.protocol!=='https:'||origin.origin!==config.managementOrigin)throw Error('A canonical HTTPS management origin is required.');
let html=await fs.readFile(path.join(root,'backend/built-preview.html'),'utf8');
html=html.replace('<body>',()=>'<body><script>window.PQ_PUBLIC_SITE='+JSON.stringify({origin:origin.origin}).replace(/</g,'\\u003c')+';</script>');
html=html.replace('허용된 이메일과 플래너 전용 비밀번호로 로그인해요.','로그인하고 관리 버튼으로 관리 화면을 열 수 있어요. 허용된 이메일만 수정할 수 있어요.');
const output=path.join(root,'public-site');await fs.mkdir(output,{recursive:true});
await fs.writeFile(path.join(output,'index.html'),html);
await fs.writeFile(path.join(output,'.nojekyll'),'');
await fs.copyFile(path.join(root,'publish/robots.txt'),path.join(output,'robots.txt'));
console.log('Built GitHub Pages viewer with the existing authenticated management site.');
